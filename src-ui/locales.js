export function translate(language, key) {
  return i18n[language]?.[key] ?? i18n.en[key] ?? key;
}

export function getMissingTranslationKeys(language, keys = Object.keys(i18n.en)) {
  const catalog = i18n[language] || {};
  return keys.filter((key) => typeof catalog[key] !== "string" || catalog[key].trim() === "");
}
